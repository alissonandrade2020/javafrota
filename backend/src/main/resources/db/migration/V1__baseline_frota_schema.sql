CREATE TABLE proprietarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    documento VARCHAR(20) NOT NULL UNIQUE,
    telefone VARCHAR(30),
    email VARCHAR(140),
    cidade VARCHAR(80),
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE funcionarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(140) NOT NULL UNIQUE,
    telefone VARCHAR(30),
    cargo VARCHAR(50) NOT NULL,
    setor VARCHAR(30) NOT NULL,
    perfil VARCHAR(24) NOT NULL,
    status VARCHAR(20) NOT NULL,
    data_admissao DATE
);

CREATE TABLE pecas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(40) NOT NULL UNIQUE,
    nome VARCHAR(120) NOT NULL,
    categoria VARCHAR(60) NOT NULL,
    quantidade INTEGER NOT NULL,
    estoque_minimo INTEGER NOT NULL,
    custo_unitario NUMERIC(12, 2) NOT NULL,
    fornecedor VARCHAR(100)
);

CREATE TABLE veiculos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    marca VARCHAR(80) NOT NULL,
    modelo VARCHAR(100) NOT NULL,
    ano INTEGER NOT NULL,
    placa VARCHAR(20) NOT NULL UNIQUE,
    status VARCHAR(30) NOT NULL,
    cor VARCHAR(40),
    combustivel VARCHAR(30),
    categoria VARCHAR(30),
    imagem_url VARCHAR(500),
    problema_atual VARCHAR(500),
    recarga_externa BOOLEAN,
    autonomia_eletrica_km INTEGER,
    fonte_imagem VARCHAR(180),
    proprietario_id BIGINT REFERENCES proprietarios(id),
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE ordens_servico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    veiculo_id BIGINT NOT NULL,
    placa VARCHAR(12) NOT NULL,
    veiculo VARCHAR(120) NOT NULL,
    proprietario VARCHAR(120),
    problema VARCHAR(500) NOT NULL,
    diagnostico VARCHAR(1000),
    prioridade VARCHAR(20) NOT NULL,
    status VARCHAR(24) NOT NULL,
    responsavel VARCHAR(120),
    custo NUMERIC(12, 2) NOT NULL,
    mao_de_obra NUMERIC(12, 2) NOT NULL,
    abertura DATE NOT NULL,
    previsao_conclusao DATE
);

CREATE TABLE itens_ordem_servico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_id BIGINT NOT NULL REFERENCES ordens_servico(id),
    peca_id BIGINT NOT NULL REFERENCES pecas(id),
    sku VARCHAR(40) NOT NULL,
    nome_peca VARCHAR(120) NOT NULL,
    quantidade INTEGER NOT NULL,
    valor_unitario NUMERIC(12, 2) NOT NULL,
    subtotal NUMERIC(12, 2) NOT NULL
);

CREATE TABLE vendas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente VARCHAR(120) NOT NULL,
    veiculo VARCHAR(120) NOT NULL,
    placa VARCHAR(12) NOT NULL,
    vendedor VARCHAR(120) NOT NULL,
    status VARCHAR(24) NOT NULL,
    valor NUMERIC(12, 2) NOT NULL,
    data DATE NOT NULL,
    observacoes VARCHAR(300)
);
